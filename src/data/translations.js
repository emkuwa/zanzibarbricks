export function tr(lang, key, replacements = {}) {
  const text = translations[lang]?.[key] ?? translations.en[key] ?? key
  return Object.keys(replacements).reduce((s, k) => s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(replacements[k])), text)
}
